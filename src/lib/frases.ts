export function fraseDelDia(fecha: Date = new Date()): string {
  const inicioDeAnio = new Date(fecha.getFullYear(), 0, 1);
  const diaDelAnio = Math.floor((fecha.getTime() - inicioDeAnio.getTime()) / 86_400_000);
  return FRASES_MOTIVADORAS[diaDelAnio % FRASES_MOTIVADORAS.length];
}
